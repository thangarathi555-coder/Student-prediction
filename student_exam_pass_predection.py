encoder = LabelEncoder()

categorical_cols = [
    "Gender",
    "Parental_Education_Level",
    "Internet_Access_at_Home",
    "Extracurricular_Activities",
    "Pass_Fail"
]

for col in categorical_cols:
    df[col] = encoder.fit_transform(df[col])

plt.figure(figsize=(10,6))

numeric_df = df.select_dtypes(include=['int64','float64'])

sns.heatmap(
    numeric_df.corr(),
    annot=True,
    cmap="coolwarm"
)

plt.title("Correlation Heatmap")
plt.show()

def risk_category(row):

    if (
        row["Attendance_Rate"] < 60 and
        row["Study_Hours_per_Week"] < 10 and
        row["Past_Exam_Scores"] < 50
    ):
        return "High Risk"

    elif (
        row["Attendance_Rate"] < 80 and
        row["Past_Exam_Scores"] < 70
    ):
        return "Medium Risk"

    else:
        return "Low Risk"

df["Risk_Category"] = df.apply(risk_category, axis=1)

print("\nRisk Category Count")
print(df["Risk_Category"].value_counts())

plt.figure(figsize=(6,4))
sns.countplot(
    x="Risk_Category",
    data=df
)
plt.title("Student Risk Categories")
plt.show()

if "Student_ID" in df.columns:
    df.drop("Student_ID", axis=1, inplace=True)

X = df.drop(
    ["Pass_Fail", "Risk_Category"],
    axis=1
)

y = df["Pass_Fail"]

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(
    X_scaled,
    y,
    test_size=0.2,
    random_state=42
)

model = LogisticRegression(max_iter=1000)

model.fit(X_train, y_train)

y_pred = model.predict(X_test)

y_prob = model.predict_proba(X_test)[:,1]

print("\n===== MODEL PERFORMANCE =====")

print("Accuracy:",
      accuracy_score(y_test, y_pred))

print("Precision:",
      precision_score(y_test, y_pred))

print("Recall:",
      recall_score(y_test, y_pred))

print("F1 Score:",
      f1_score(y_test, y_pred))

print("ROC AUC Score:",
      roc_auc_score(y_test, y_prob))

print("\nConfusion Matrix")
cm = confusion_matrix(y_test, y_pred)
print(cm)

print("\nClassification Report")
print(classification_report(y_test, y_pred))

plt.figure(figsize=(6,4))
